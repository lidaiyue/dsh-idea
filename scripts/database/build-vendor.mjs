// Bundle the CodeMirror 6 stack into `lib/database/vendor/codemirror.js`.
//
// The artifact is committed and shipped inside the package, because the plugin has
// no build step at install time: DSH serves `lib/client.js` as-is and the host never
// runs a bundler for plugins. Re-run this only when the CodeMirror deps change:
//
//   npm run build:vendor
//
// Format is a classic IIFE, not ESM, so the browser half can load it with a plain
// <script> tag from the plugin's own route (no import maps, no module graph entry).
import { build } from "esbuild";
import { mkdir, stat, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const out = join(root, "lib", "database", "vendor", "codemirror.js");

await mkdir(dirname(out), { recursive: true });

const result = await build({
  entryPoints: [join(here, "vendor-entry.js")],
  bundle: true,
  format: "iife",
  target: "es2020",
  minify: true,
  legalComments: "none",
  // One self-contained file: nothing here may resolve at runtime, because the
  // browser half has no module system for it to resolve against.
  write: false,
});

const [artifact] = result.outputFiles;
const banner = "/* dsh-idea database console: bundled CodeMirror 6. Generated by scripts/database/build-vendor.mjs — do not edit. */\n";
await writeFile(out, banner + artifact.text, "utf8");

const { size } = await stat(out);
const gzip = (await import("node:zlib")).gzipSync(Buffer.from(artifact.text)).length;
console.log(`wrote ${out}`);
console.log(`  raw   ${(size / 1024).toFixed(1)} kB`);
console.log(`  gzip  ${(gzip / 1024).toFixed(1)} kB`);
